const LOCAL_STORAGE_KEY = 'nakhon_stray_habitats_data_v1';

/**
 * โหลดข้อมูลแหล่งอาหาร/ที่อยู่สัตว์จรจัด (รวมข้อมูลเริ่มต้น + ข้อมูลที่ผู้ใช้บันทึกเพิ่ม)
 */
export function getStrayHabitats(): StrayHabitatFoodSource[] {
  try {
    const saved = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // Merge seeds that are not in parsed to ensure complete base dataset
        const customItems = parsed.filter((item: StrayHabitatFoodSource) => item.isCustomAdded);
        return [...SEED_STRAY_HABITATS, ...customItems];
      }
    }
  } catch (err) {
    console.warn('Failed to load saved stray habitats from localStorage', err);
  }
  return SEED_STRAY_HABITATS;
}

/**
 * บันทึกรายการแหล่งอาหาร/ที่อยู่สัตว์จรจัดใหม่ลงระบบ
 */
export function saveCustomStrayHabitat(newHabitat: StrayHabitatFoodSource): StrayHabitatFoodSource[] {
  try {
    const current = getStrayHabitats();
    const existingIdx = current.findIndex(h => h.id === newHabitat.id);
    let updated: StrayHabitatFoodSource[];
    if (existingIdx >= 0) {
      updated = [...current];
      updated[existingIdx] = { ...newHabitat, isCustomAdded: true };
    } else {
      updated = [{ ...newHabitat, isCustomAdded: true }, ...current];
    }
    const customOnly = updated.filter(h => h.isCustomAdded);
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(customOnly));
    return updated;
  } catch (err) {
    console.error('Failed to save stray habitat', err);
    return getStrayHabitats();
  }
}

/**
 * ลบรายการที่ผู้ใช้สร้าง
 */
export function deleteCustomStrayHabitat(id: string): StrayHabitatFoodSource[] {
  try {
    const current = getStrayHabitats();
    const updated = current.filter(h => h.id !== id);
    const customOnly = updated.filter(h => h.isCustomAdded);
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(customOnly));
    return updated;
  } catch (err) {
    console.error('Failed to delete custom stray habitat', err);
    return getStrayHabitats();
  }
}

/**
 * สรุปตัวเลขสถิติแหล่งอาหาร/สัตว์จรจัด
 */
export function getStrayHabitatsSummary(data: StrayHabitatFoodSource[] = SEED_STRAY_HABITATS) {
  const totalLocations = data.length;
  const totalDogs = data.reduce((acc, h) => acc + (h.estimatedDogs || 0), 0);
  const totalCats = data.reduce((acc, h) => acc + (h.estimatedCats || 0), 0);
  const totalAnimals = totalDogs + totalCats;
  
  const criticalCount = data.filter(h => h.riskLevel === 'CRITICAL').length;
  const highCount = data.filter(h => h.riskLevel === 'HIGH').length;
  const mediumCount = data.filter(h => h.riskLevel === 'MEDIUM').length;
  const lowCount = data.filter(h => h.riskLevel === 'LOW').length;

  const marketCount = data.filter(h => h.category === 'market').length;
  const landfillCount = data.filter(h => h.category === 'waste_landfill').length;
  const templeCount = data.filter(h => h.category === 'temple').length;
  const govCount = data.filter(h => h.category === 'government_public').length;
  const portCount = data.filter(h => h.category === 'fishing_port').length;

  const openDumpCount = data.filter(h => h.wasteManagementStatus === 'OPEN_DUMP').length;
  const needsInterventionCount = data.filter(h => h.actionStatus === 'NEEDS_INTERVENTION').length;

  const avgVaccine = data.length > 0
    ? data.reduce((acc, h) => acc + (h.vaccinationCoverage || 0), 0) / data.length
    : 0;

  return {
    totalLocations,
    totalDogs,
    totalCats,
    totalAnimals,
    criticalCount,
    highCount,
    mediumCount,
    lowCount,
    categoryCounts: {
      market: marketCount,
      waste_landfill: landfillCount,
      temple: templeCount,
      government_public: govCount,
      fishing_port: portCount,
    },
    openDumpCount,
    needsInterventionCount,
    avgVaccine,
  };
}

