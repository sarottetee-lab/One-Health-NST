/**
 * ฟังก์ชันตรวจสอบความตรงกันของตำบล (รองรับทั้งคำว่า "ตำบล...", "ต...." และชื่อย่อ)
 */
export function matchSubDistrict(itemSubDistrict: string | undefined | null, selectedSubDistrict: string): boolean {
  if (!selectedSubDistrict || selectedSubDistrict === 'all') return true;
  if (!itemSubDistrict) return false;
  const cleanItem = itemSubDistrict.replace(/^ต\./, '').replace(/^ตำบล/, '').trim().toLowerCase();
  const cleanSelected = selectedSubDistrict.replace(/^ต\./, '').replace(/^ตำบล/, '').trim().toLowerCase();
  return cleanItem.includes(cleanSelected) || cleanSelected.includes(cleanItem);
}

/**
 * ฟังก์ชันตรวจสอบความตรงกันของหมู่ที่ / หมู่บ้าน (รองรับ "หมู่ 1", "หมู่ที่ 1", "Moo 1" และชื่อหมู่บ้าน)
 */
export function matchVillage(itemVillage: string | undefined | null, selectedVillage: string): boolean {
  if (!selectedVillage || selectedVillage === 'all') return true;
  if (!itemVillage) return false;

  const target = selectedVillage.trim().toLowerCase();
  const source = itemVillage.trim().toLowerCase();

  // 1. Direct substring match
  if (source.includes(target) || target.includes(source)) return true;

  // 2. Match Moo number (e.g., "หมู่ 1", "หมู่ที่ 1", "Moo 1")
  const targetMooMatch = target.match(/(?:หมู่|หมู่ที่|moo)\s*(\d+)/i);
  const sourceMooMatch = source.match(/(?:หมู่|หมู่ที่|moo)\s*(\d+)/i);

  if (targetMooMatch && sourceMooMatch) {
    if (targetMooMatch[1] === sourceMooMatch[1]) return true;
  }

  // 3. Match village name without prefix
  const cleanTarget = target.replace(/^(?:หมู่|หมู่ที่|moo)\s*\d+\s*(?:บ้าน)?/i, '').trim();
  if (cleanTarget.length > 2 && source.includes(cleanTarget)) {
    return true;
  }

  return false;
}

