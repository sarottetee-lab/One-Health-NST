/**
 * ดึงพิกัด Lat/Lng เพื่อสั่ง Zoom อัตโนมัติในแผนที่ OpenStreetMap
 */
export function getLocationCoordinates(
  districtName: string,
  subDistrictName: string = 'all'
): { lat: number; lng: number; zoom: number } {
  // 1. If specific SubDistrict selected
  if (subDistrictName && subDistrictName !== 'all') {
    const foundSub = SUBDISTRICT_GEODATA[subDistrictName];
    if (foundSub) {
      return { lat: foundSub.lat, lng: foundSub.lng, zoom: 14 };
    }
  }

  // 2. If specific District selected
  if (districtName && districtName !== 'all') {
    const foundDist = NAKHON_DISTRICTS.find(
      (d) => d.nameTh.includes(districtName) || districtName.includes(d.nameTh)
    );
    if (foundDist) {
      return { lat: foundDist.lat, lng: foundDist.lng, zoom: 12 };
    }
  }

  // 3. Default entire Nakhon Si Thammarat Province
  return { lat: 8.4304, lng: 99.9631, zoom: 10 };
}

/**
 * ดึงรายชื่อตำบลตามอำเภอ
 */
export function getSubDistrictsByDistrict(districtName: string): string[] {
  if (!districtName || districtName === 'all') {
    // Return all subdistricts
    const allSubs = new Set<string>();
    NAKHON_DISTRICTS.forEach((d) => d.subDistricts.forEach((s) => allSubs.add(s)));
    return Array.from(allSubs);
  }
  const dist = NAKHON_DISTRICTS.find((d) => d.nameTh.includes(districtName) || districtName.includes(d.nameTh));
  return dist ? dist.subDistricts : [];
}

